    public void actualizarLista(){
          txaLista.setText(""); 
          listaTexto = "";
          for(Producto p:listaProductos){
              listaTexto += p.getNombre() + " $" + p.getPrecio() + "(" + p.getStock()  + ") \n";             
          }
          txaLista.setText(listaTexto);
          txtNombre.setText("");
          txtMarca.setText("");        
          txtStock.setText("");
          
          
          txtNombre.requestFocusInWindow();
    }
